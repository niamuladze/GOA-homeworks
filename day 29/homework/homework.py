# 1) ფუნქცია - აბრუნებს სიიდან მხოლოდ კენტი რიცხვების ჯამს
def sum_of_odds(numbers):
    total = 0
    for num in numbers:
        if num % 2 != 0:
            total += num
    return total

# 2) ფუნქცია - აბრუნებს სიიდან იმ სახელებს რომლებიც 4 ასოსგან შედგება
def names_with_four_letters(names):
    result = []
    for name in names:
        if len(name) == 4:
            result.append(name)
    return result

# 3) ფუნქცია - აბრუნებს რიცხვებს რომლებიც იყოფა 3-ზეც და 5-ზეც
def divisible_by_3_and_5(numbers):
    result = []
    for num in numbers:
        if num % 3 == 0 and num % 5 == 0:
            result.append(num)
    return result

