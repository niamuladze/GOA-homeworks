# 1) ფუნქცია, რომელიც ბეჭდავს ორი რიცხვის ჯამს
def print_sum(a, b):
    print("რიცხვების ჯამია:", a + b)

# 2) ფუნქცია, რომელიც იღებს სახელს და ბეჭდავს მისალმებას
def greet_user(name):
    print("გამარჯობა,", name + "!")

# 3) ფუნქცია, რომელიც იღებს 5 პარამეტრს და ბეჭდავს მათ
def print_five_values(val1, val2, val3, val4, val5):
    print("პარამეტრი 1:", val1)
    print("პარამეტრი 2:", val2)
    print("პარამეტრი 3:", val3)
    print("პარამეტრი 4:", val4)
    print("პარამეტრი 5:", val5)

# ფუნქციების გამოძახება (მაგალითები):

# 1) ორი რიცხვის ჯამი
print_sum(5, 7)  # რიცხვების ჯამია: 12

# 2) მისალმება სახელით
greet_user("ნაომი")  # გამარჯობა, ნაომი!

# 3) 5 მნიშვნელობის ბეჭდვა
print_five_values("яблоко", 123, True, 3.14, "hello")
# გამოიტანს:
# პარამეტრი 1: яблоко
# პარამეტრი 2: 123
# პარამეტრი 3: True
# პარამეტრი 4: 3.14
# პარამეტრი 5: hello
