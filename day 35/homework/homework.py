# 2) Custom ფუნქციები

# Custom (მომხმარებლის მიერ შექმნილი) ფუნქცია არის ისეთი ფუნქცია, რომელსაც თავად პროგრამისტი ქმნის.
# ის საშუალებას გვაძლევს დავაკავშიროთ კონკრეტული ლოგიკა ერთ სახელთან და გამოვიყენოთ რამდენჯერმე.
# ფუნქცია იქმნება def-ს მეშვეობით. მას შეიძლება ჰქონდეს პარამეტრები და შედეგის დაბრუნება (return).

# ფუნქციის შექმნის ეტაპები:
# 1. გამოვიყენოთ def საკვანძო სიტყვა
# 2. დავარქვათ სახელი
# 3. პარენტეზებში დავწეროთ საჭირო პარამეტრები
# 4. ფრჩხილების შიგნით დავწეროთ კოდი
# 5. სურვილის მიხედვით დავაბრუნოთ შედეგი return-ით


# 3) ფუნქცია, რომელიც აბრუნებს ორი რიცხვის ჯამს
def sum_two_numbers(a, b):
    return a + b


# 4) ფუნქცია, რომელიც ამოწმებს რიცხვის ლუწობას
def check_even(num):
    if num % 2 == 0:
        print("რიცხვი ლუწია")
    else:
        print("რიცხვი კენტია")


# 5) ფუნქცია, რომელიც აბრუნებს რიცხვის კვადრატს
def square(num):
    return num ** 2


# 6) ფუნქცია, რომელიც აბრუნებს ტექსტს დიდი ასოებით
def to_uppercase(text):
    return text.upper()


# 7) ფუნქცია, რომელიც ბეჭდავს სახელს და გვარს ერთ წინადადებაში
def full_intro(name, surname):
    print(f"მე ვარ {name} {surname}. სასიამოვნოა თქვენი გაცნობა!")


# გამოსაყენებელი მაგალითები:
# 3)
print(sum_two_numbers(3, 7))  # 10

# 4)
check_even(6)  # რიცხვი ლუწია
check_even(9)  # რიცხვი კენტია

# 5)
print(square(5))  # 25

# 6)
print(to_uppercase("hello world"))  # HELLO WORLD

# 7)
full_intro("ნაომი", "მარგოლის")  # მე ვარ ნაომი მარგოლის. სასიამოვნოა თქვენი გაცნობა!
