def word_len(sentance):
    result = []      # საბოლოო შედეგის სია
    words = ""       # დროებითი ცვლადი სიტყვის შესაგროვებლად

    for i in sentance:          # წინადადების თითო სიმბოლოზე ვატარებთ იტერაციას
        if i != " ":            # თუ სიმბოლო არ არის სივრცე (" ")
            words += i          # ვამატებთ მას მიმდინარე სიტყვაში
        else:                   # როცა სივრცე ვნახეთ — ესე იგი სიტყვა დასრულდა
            result.append(words + str(len(words)))  # ვამატებთ სიტყვას და მის სიგრძეს
            words = ""          # ვცლით ცვლადს შემდეგი სიტყვისთვის

    result.append(words + str(len(words)))  # ბოლო სიტყვაც ვამატებთ ციკლის გარეთ
    print(result)                           # ვბეჭდავთ შედეგს
